test("evidence drawer traps focus and restores it on Escape", async ({ page }) => {
  await page.goto("/"); await page.getByRole("button", { name: /Evidence intelligence/ }).click();
  const opener = page.getByRole("button", { name: /Three accounts reused one beneficiary/ }); await opener.click();
  const dialog = page.getByRole("dialog", { name: /Three accounts reused one beneficiary/ }); await expect(dialog).toBeVisible();
  await page.keyboard.press("Tab"); await expect(page.locator("[role=dialog] button:focus, [role=dialog] textarea:focus")).toHaveCount(1);
  await page.keyboard.press("Escape"); await expect(dialog).toBeHidden(); await expect(opener).toBeFocused();
});

